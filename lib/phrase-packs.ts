/** 이 달(1–12)에 나올 수 있는 팩 문구. 계절 필터로 비면 전체. */
export function packPhrases(packId: string, month: number): PackPhrase[] {
  const all = PHRASE_PACKS[packId]?.phrases ?? [];
  const now = all.filter((p) => !p.months || p.months.includes(month));
  return now.length > 0 ? now : all;
}
