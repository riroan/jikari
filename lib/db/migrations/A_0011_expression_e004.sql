      note_ko = '「〜なんですね」는 눈치챈 것을 부드럽게 확인하는 어미. 사람을 좋아한다고 할 때는 「彼女が」보다 「彼女のことが」가 자연스럽고, 상대를 가리키는 あなた는 보통 생략한다'
